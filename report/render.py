@dataclass(frozen=True)
class Selection:
    """The clauses after a table's name: rows kept, then grouped and aggregated."""

    where: tuple[tuple[str, str], ...] = ()
    aggregate: str | None = None  # "sum" or "mean"
    columns: tuple[str, ...] = ()  # the aggregated columns
    by: tuple[str, ...] = ()
    across: str | None = None


def parse_selection(words: list[str]) -> Selection:
    """``where col=value ... [sum|mean col,col by col,col [across col]]``, in that order."""
    found: dict[str, list[str]] = {}
    current = None
    for word in words:
        if word in CLAUSES:
            if current is not None and CLAUSE_ORDER[word] <= CLAUSE_ORDER[current]:
                raise ValueError(f"the {word!r} clause cannot follow {current!r} (the order "
                                 "is where, sum or mean, by, across; each once)")
            current = word
            found[word] = []
        elif current is None:
            raise ValueError(f"{word!r} is not a clause; use where, sum, mean, by or across")
        else:
            found[current].append(word)

    def names(clause: str) -> tuple[str, ...]:
        items = tuple(item.strip() for item in " ".join(found[clause]).split(","))
        if not all(KEY.fullmatch(item) and "." not in item for item in items):
            raise ValueError(f"{clause}: name columns separated by commas, got "
                             f"{' '.join(found[clause])!r}")
        return items

    where = []
    for item in found.get("where", []):
        column, equals, wanted = item.partition("=")
        if not equals or not column or not wanted:
            raise ValueError(f"where: {item!r} is not column=value")
        where.append((column, wanted))
    if "where" in found and not where:
        raise ValueError("where: name at least one column=value")
    aggregate = "sum" if "sum" in found else "mean" if "mean" in found else None
    if aggregate is None and ("by" in found or "across" in found):
        raise ValueError("by and across follow sum or mean")
    if aggregate is not None and "by" not in found:
        raise ValueError(f"{aggregate} needs by: the columns that make a group")
    selection = Selection(
        where=tuple(where), aggregate=aggregate,
        columns=names(aggregate) if aggregate else (),
        by=names("by") if aggregate else (),
        across=None)
    if "across" in found:
        if aggregate != "sum":
            raise ValueError("across spreads a sum, not a mean")
        if len(found["across"]) != 1 or len(selection.columns) != 1:
            raise ValueError("across takes one column, and sums one column")
        selection = Selection(selection.where, aggregate, selection.columns, selection.by,
                              found["across"][0])
    return selection


def _text(cell: Any) -> str:
    """A cell as a where clause reads it."""
    if isinstance(cell, bool):
        return "true" if cell else "false"
    return "null" if cell is None else str(cell)


def aggregation_refused(table_name: str, column: str, how: str) -> str | None:
    """Why ``column`` of the result table ``table_name`` cannot be summed or averaged over
    its rows, or ``None`` (see :data:`AGGREGABLE`)."""
    allowed = AGGREGABLE.get(table_name)
    if allowed is None:
        return (f"{table_name!r} holds figures already pooled or averaged over seeds, or no "
                "per-world values: use its result keys, not a sum or mean of its rows")
    if column in allowed[how]:
        return None
    if how == "sum" and column in allowed["mean"]:
        return f"{column!r} is a per-world level, which does not add up: use mean"
    if how == "mean" and column in allowed["sum"]:
        return (f"{column!r} adds up over worlds: use sum, or its pooled result key for an "
                "average")
    return (f"{column!r} is not a count or money column of {table_name!r} that adds up "
            "over worlds, nor a per-world level")


def _number(cell: Any, column: str) -> int | float | None:
    if cell is None:
        return None
    if isinstance(cell, bool) or not isinstance(cell, int | float):
        raise ValueError(f"column {column!r} holds {cell!r}, not a number")
    return cell


def _aggregate(cells: list[Any], how: str, column: str) -> int | float | None:
    numbers = [_number(cell, column) for cell in cells]
    if any(number is None for number in numbers):
        return None  # a row with nothing measured leaves its group's figure unknown
    total = sum(numbers)
    return total if how == "sum" else total / len(numbers)


WORLD_KEYS = ("seed", "family", "policy")  # a policy's replay of one world


def unevaluated_worlds(summary: Mapping[str, Any]) -> list[dict[str, Any]]:
    """The policies' worlds the replay did not evaluate (``replay.outcomes`` rows with
    ``evaluated`` false: no feasible operating point on that seed), by seed, family and
    policy; the per-world tables hold no rows, or rows of nulls, for them."""
    try:
        rows = table(summary, "replay.outcomes")
    except KeyError:
        return []
    return [{key: row.get(key) for key in WORLD_KEYS} for row in rows
            if row.get("evaluated") is False]


def select(rows: list[dict[str, Any]], selection: Selection, name: str,
           unevaluated: list[dict[str, Any]] = ()
           ) -> tuple[list[dict[str, Any]], dict[str, str | None], set[str]]:
    """The rows ``selection`` keeps and aggregates, the units of spread columns, and
    which of them hold paired differences; raises :class:`RenderError` listing every
    problem.

    An aggregation whose selection reaches a world in ``unevaluated`` (one the ``where``
    clauses on seed, family and policy do not exclude) fails: its total would leave that
    world out, or count its absent rows as zero, without saying so.
    """
    problems = []
    columns = set(rows[0]) if rows else set()
    named = [column for column, _ in selection.where] + list(selection.by) + \
        list(selection.columns) + ([selection.across] if selection.across else [])
    problems += [f"no column {column!r}" for column in dict.fromkeys(named)
                 if column not in columns]
    if selection.aggregate:
        problems += [reason for column in selection.columns
                     if (reason := aggregation_refused(name, column, selection.aggregate))]
        if overlap := set(selection.columns) & set(selection.by):
            problems.append(f"{sorted(overlap)} both group and are aggregated")
        scope = {column: wanted for column, wanted in selection.where if column in WORLD_KEYS}
        for world in unevaluated:
            if all(_text(world.get(column)) == wanted for column, wanted in scope.items()):
                problems.append(
                    f"policy {world.get('policy')!r} was not evaluated on seed "
                    f"{world.get('seed')} ({world.get('family')}), which this selection "
                    "reaches: a total over worlds would leave it out; narrow the selection")
    if problems:
        raise RenderError(f"table {name!r}", problems)
    kept = [row for row in rows
            if all(_text(row.get(column)) == wanted for column, wanted in selection.where)]
    if not kept:
        wanted = " ".join(f"{column}={value}" for column, value in selection.where)
        raise RenderError(f"table {name!r}", [f"no rows match where {wanted}"])
    if not selection.aggregate:
        return kept, {}, set()
    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = {}
    for row in kept:
        groups.setdefault(tuple(row.get(column) for column in selection.by), []).append(row)
    # groups in the order their values first appear in the whole table, so that every
    # selection from one table lists its groups in the same order
    first = [{value: rank for rank, value in
              enumerate(dict.fromkeys(row.get(column) for row in rows))}
             for column in selection.by]
    groups = dict(sorted(groups.items(), key=lambda item: tuple(
        rank[value] for rank, value in zip(first, item[0], strict=True))))
    out = []
    try:
        if selection.across:
            [summed] = selection.columns
            spread = list(dict.fromkeys(row.get(selection.across) for row in kept))
            titles = [_text(value) for value in spread]
            if unnamed := sorted({title for title in titles if not NAME.fullmatch(title)}):
                raise ValueError(f"across {selection.across}: the values {unnamed} cannot "
                                 "name a column (lower-case letters, digits and _)")
            if len(set(titles)) != len(titles):
                raise ValueError(f"across {selection.across}: values that differ print as "
                                 "the same column name")
            if clash := set(titles) & {*selection.by, ROWS_COUNT}:
                raise ValueError(f"spread columns {sorted(clash)} clash with the groups or "
                                 f"{ROWS_COUNT}")
            for key, members in groups.items():
                record = dict(zip(selection.by, key, strict=True))
                for value, title in zip(spread, titles, strict=True):
                    cells = [row.get(summed) for row in members
                             if row.get(selection.across) == value]
                    record[title] = _aggregate(cells, "sum", summed) if cells else 0
                record[ROWS_COUNT] = len(members)
                out.append(record)
            unit = formats.unit_from_name(summed)
            return out, {title: unit for title in titles}, (
                set(titles) if "_vs_" in summed else set())
        for key, members in groups.items():
            record = dict(zip(selection.by, key, strict=True))
            for column in selection.columns:
                record[column] = _aggregate([row.get(column) for row in members],
                                            selection.aggregate, column)
            record[ROWS_COUNT] = len(members)
            out.append(record)
    except ValueError as error:
        raise RenderError(f"table {name!r}", [str(error)]) from error
    return out, {}, set()


def _labels(data: Any) -> dict[str, str]:
    labels = dict(data or {})
    for key, text in labels.items():
        if not isinstance(key, str) or not isinstance(text, str) or not text:
            raise ValueError(f"wording.labels.{key}: give the words as text")
    return labels


def label(identifier: str, labels: Mapping[str, str]) -> str:
    """An identifier, or a comma-separated list of them, in words: its entry in
    ``wording.labels``, else its words split at underscores; an empty list is "none"."""
    if not identifier.strip():
        return "none"
    return ", ".join(labels.get(item, item.replace("_", " "))
                     for item in (part.strip() for part in identifier.split(",")))


def _fact_rows(expression: str, sources: Sources) -> list[dict[str, Any]]:
    node, _ = _fact(expression, sources)
    if not isinstance(node, list) or not all(isinstance(row, Mapping) for row in node):
        raise KeyError(f"case fact {expression!r} is not a list of records")
    return [dict(row) for row in node]


def render_facts(body: str, sources: Sources) -> str:
    """Render ``facts:<file>:<path> ["Header" "Header"] | name "Label" format, ...``: one
    row per named single value of the record at the path, each formatted in the unit of
    its own name; raises :class:`RenderError` listing every problem."""
    head, _, spec = body.partition("|")
    match = FACTS_HEAD.fullmatch(head.strip())
    if not match:
        raise KeyError(f"{head.strip()!r} is not facts:<file>:<dotted.path>")
    expression, first, second = match.groups()
    record, _ = _fact(expression, sources)
    if not isinstance(record, Mapping):
        raise KeyError(f"case fact {expression!r} is not a record")
    problems: list[str] = []
    lines = [f"| {first or 'Fact'} | {second or 'Value'} |", "|---|---:|"]
    for item in spec.split(",") if spec.strip() else []:
        found = COLUMN.match(item)
        if not found:
            problems.append(f"bad entry {item.strip()!r}")
            continue
        key, label, form = found.groups()
        format_name, *args = (form or "value").split(":")
        if format_name not in formats.FORMATS:
            problems.append(f"unknown format {format_name!r} for fact {key!r}")
            continue
        if key not in record:
            problems.append(f"no fact {key!r} in {expression!r}")
            continue
        value = record[key]
        if isinstance(value, Mapping | list):
            problems.append(f"fact {key!r} is not a single value")
            continue
        if value is None:
            problems.append(f"fact {key!r} is null")
            continue
        if isinstance(value, bool):
            if form is not None:
                problems.append(f"fact {key!r} is yes or no and takes no format")
                continue
            cell = "yes" if value else "no"
        else:
            try:
                cell = formats.apply(format_name, Value(plain=value,
                                                        unit=formats.unit_from_name(key)), args)
            except FormatError as error:
                problems.append(f"fact {key!r}: {error}")
                cell = ""
        lines.append(f"| {label or key} | {cell} |")
    if len(lines) == 2 and not problems:
        problems.append("no facts named")
    if problems:
        raise RenderError(f"facts {expression!r}", problems)
    return "\n".join(lines)


def render(text: str, sources: Sources, name: str = "template") -> str:
    """Render a template's text; raises :class:`RenderError` listing every problem."""
    problems: list[str] = []
    out_lines = []
    for number, line in enumerate(text.split("\n"), start=1):
        stripped = line.strip()
        block = PLACEHOLDER.fullmatch(stripped)
        if block and block.group(1).strip().startswith(("table:", "facts:")):
            render_block = render_facts if block.group(1).strip().startswith("facts:") \
                else render_table
            try:
                out_lines.append(render_block(block.group(1), sources))
            except (KeyError, FormatError, ValueError) as error:
                problems.append(f"line {number}: {_message(error)}")
            continue

        def replace(match: re.Match[str], number: int = number) -> str:
            body = match.group(1)
            if body.strip().startswith(("table:", "facts:")):
                problems.append(f"line {number}: a table placeholder must be on its own line")
                return ""
            try:
                return render_value(body, sources)
            except (KeyError, FormatError, ValueError) as error:
                problems.append(f"line {number}: {{{{{body.strip()}}}}}: {_message(error)}")
                return ""

        out_lines.append(PLACEHOLDER.sub(replace, line))
    if "{{" in "\n".join(out_lines) or "}}" in "\n".join(out_lines):
        problems.append("unbalanced placeholder braces")
    if problems:
        raise RenderError(name, problems)
    return "\n".join(out_lines)


def _message(error: Exception) -> str:
    return str(error.args[0]) if isinstance(error, KeyError) and error.args else str(error)


@dataclass(frozen=True)
class Document:
    template: Path
    output: Path

    @property
    def name(self) -> str:
        return self.output.as_posix()


def documents(templates: Path = TEMPLATES) -> list[Document]:
    """Every template and the repository path of the document it produces."""
    return [
        Document(template=path, output=path.relative_to(templates))
        for path in sorted(templates.rglob("*.md"))
    ]


def render_document(document: Document, sources: Sources, root: Path = REPO) -> str:
    """The full text of a rendered document, with the generated-file header."""
    template = document.template
    template_name = (template.relative_to(root).as_posix() if template.is_relative_to(root)
                     else template.name)
    body = render(document.template.read_text(), sources, document.name)
    return HEADER.format(template=template_name) + body


NOT_RENDERED = "NOT_RENDERED.txt"


def render_all(sources: Sources, out_root: Path, templates: Path = TEMPLATES,
               root: Path = REPO, *, strict: bool = False) -> list[Path]:
    """Render every template into ``out_root``; returns the paths written.

    Into the repository (``out_root`` is ``root`` or :data:`REPO`), or with ``strict``,
    a document that cannot be rendered fails the render and nothing is written.
    Anywhere else (a development or small run's ``docs`` folder) the documents whose
    result keys or case facts the run has are written, the others are skipped: they and their
    problems are listed in ``out_root/NOT_RENDERED.txt``, a copy of a skipped
    document left there by an earlier render is removed, and a one-line notice is
    printed. A render that skips nothing removes an old list. A destination that a
    link would carry outside ``out_root`` fails the render before anything is written.
    """
    out_root = Path(out_root)
    strict = strict or is_repository(out_root, root)
    targets = [doc.output for doc in documents(templates)] + [Path(NOT_RENDERED)]
    if escaping := [path.as_posix() for path in targets if not _inside(out_root, path)]:
        raise ValueError(f"{escaping} would be written outside {out_root} through a link; "
                         "nothing was written")
    rendered: dict[Document, str] = {}
    skipped: dict[Document, RenderError] = {}
    for doc in documents(templates):
        try:
            rendered[doc] = render_document(doc, sources, root)
        except RenderError as error:
            if strict:
                raise
            skipped[doc] = error
    written = []
    for doc, text in rendered.items():
        target = out_root / doc.output
        _replace(target, text)
        written.append(target)
    notice = out_root / NOT_RENDERED
    if skipped:
        lines = []
        for doc, error in skipped.items():
            (out_root / doc.output).unlink(missing_ok=True)
            lines += [f"{doc.name}:", *(f"  {problem}" for problem in error.problems)]
        _replace(notice, "Documents not rendered from this summary, and why:\n"
                 + "\n".join(lines) + "\n")
        written.append(notice)
        print(f"report: {len(skipped)} of {len(skipped) + len(rendered)} documents not "
              f"rendered from this summary (see {notice})", file=sys.stderr)
    else:
        notice.unlink(missing_ok=True)
    return written


def _replace(target: Path, text: str) -> None:
    """Write ``text`` to a new file beside ``target`` and move it into place, so a
    destination that shares its contents with another path (a hard link) is replaced,
    never written through."""
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=target.parent, prefix=f".{target.name}.")
    try:
        with os.fdopen(handle, "w") as stream:
            stream.write(text)
        os.chmod(temporary, 0o644)
        os.replace(temporary, target)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def is_repository(path: Path, root: Path = REPO) -> bool:
    """Whether ``path`` is the repository (``root`` or :data:`REPO`): the same directory
    on disk, whatever spelling, case or link leads to it."""
    path = Path(path)
    for place in {Path(root), REPO}:
        if path.resolve() == place.resolve():
            return True
        try:
            if path.exists() and place.exists() and path.samefile(place):
                return True
        except OSError:
            continue
    return False


def _inside(out_root: Path, relative: Path) -> bool:
    """Whether ``out_root / relative`` stays under ``out_root`` once links are resolved
    (a folder on the way that links elsewhere would carry writes and removals there)."""
    return (out_root / relative).resolve() == out_root.resolve() / relative


def out_of_sync(sources: Sources, out_root: Path, templates: Path = TEMPLATES,
                root: Path = REPO) -> list[str]:
    """Documents whose committed text differs from a fresh render."""
    problems = []
    for doc in documents(templates):
        target = out_root / doc.output
        try:
            expected = render_document(doc, sources, root)
        except RenderError as error:
            problems.append(str(error))
            continue
        if not target.exists():
            problems.append(f"{doc.name}: not rendered (run python -m report render)")
        elif target.read_text() != expected:
            problems.append(f"{doc.name}: differs from its template and the results "
                            "(run python -m report render)")
    return problems
