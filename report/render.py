"""Render documents from hand-written templates and the results summary.

A template is Markdown whose numbers come only from placeholders:

``{{ key }}`` or ``{{ key | format }}`` or ``{{ key | format:arg:arg }}``
    a metric in the results summary (``results/summary.json``), printed with a
    format from :mod:`report.formats` (by default the one that fits its unit);
``{{ first.key - second.key | pp }}``
    the difference of two metrics with the same unit (a difference of rates
    prints only as percentage points);
``{{ protocol:windows.test.start | date }}``
    a fixed definition from ``experiments/protocol.yaml``;
``{{ config:world:product.down_payment_bps | bps_pct }}``
    a fixed definition from ``config/<name>.yaml``;
``{{ table:name | column "Header" format, column "Header", ... }}``
    on a line of its own: a generated Markdown table from a result table, with
    the columns named (``format`` optional; ``label`` prints an identifier in
    words, from ``wording.labels`` in ``report/claims.yaml``, and ``id`` prints
    a seed or an order id as it is);
``{{ table:name where col=value ... sum col,col by col,col [across col] | ... }}``
    the same from selected rows of a result table (:func:`select`): ``where``
    keeps the rows whose cell reads ``value``; in the per-world tables of
    :data:`AGGREGABLE`, ``sum`` adds up counts or money over the rows of each
    ``by`` group and ``mean`` averages levels such as a world's median wait, or
    a world's orders, reviews and review minutes (per world, averaged over the
    worlds), each aggregated row with ``rows_count``, the rows it covers;
    ``across`` spreads one column's values into columns holding the sum;
``{{ cell:name [selection] | column format }}``
    inline: the one value of a result table that a selection leaves, with every
    refusal of a table's selection; it fails unless exactly one row remains;
``{{ claim:<id> }}``
    a directional claim from ``report/claims.yaml``, written from its record and
    the results with its evidence (:mod:`report.claims`); it fails to render
    when the results no longer support it;
``{{ fact:<file>:<dotted.path> | format }}``
    a case fact from ``cases/facts/<file>.json`` (a list item by its index), its
    unit from the suffix of the path's last name, like a setting;
``{{ table:fact:<file>:<dotted.path> | column "Header" format, ... }}``
    on a line of its own: a table from a list of records in a case facts file
    (a record without such a value, such as a shipment's amount, holds null and
    prints "n/a", as in result tables);
``{{ facts:<file>:<dotted.path> ["Header" "Header"] | name "Label" format, ... }}``
    on a line of its own: a two-column table of named single values of one
    record in a case facts file, each in its own unit; like ``fact:``, a named
    value that is null fails.

Rendering fails, listing every problem with its line, on a missing key, an
unknown format or a format that does not fit the unit. Templates live under
``report/templates/`` at the path of the document they produce (for example
``report/templates/README.md`` produces ``README.md``).
"""

