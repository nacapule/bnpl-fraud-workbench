REPO = Path(__file__).resolve().parent.parent
TEMPLATES = REPO / "report" / "templates"
SUMMARY = REPO / "results" / "summary.json"
FACTS = REPO / "cases" / "facts"
FACT = re.compile(r"^([a-z0-9_]+):([a-z0-9_]+(?:\.[a-z0-9_]+)*)$")
FACTS_HEAD = re.compile(r'^facts:(\S+)(?:\s+"([^"]*)"\s+"([^"]*)")?$')
PLACEHOLDER = re.compile(r"\{\{(.*?)\}\}", re.DOTALL)
COLUMN = re.compile(r'^\s*([a-z0-9_]+)\s*(?:"([^"]*)")?\s*([a-z0-9_:]+)?\s*$')
KEY = re.compile(r"^[a-z0-9_]+(\.[a-z0-9_]+)*$")
HEADER = (
    "<!-- Generated by `python -m report render` from {template}. "
    "Edit the template, not this file. -->\n"
)


class RenderError(ValueError):
    """A template could not be rendered; ``problems`` lists each one."""

    def __init__(self, name: str, problems: list[str]):
        self.problems = problems
        super().__init__(f"{name}: " + "; ".join(problems))


@dataclass
class Sources:
    """Where placeholders look values up."""

    summary: Mapping[str, Any]
    protocol: Mapping[str, Any] = field(default_factory=dict)
    configs: Mapping[str, Mapping[str, Any]] = field(default_factory=dict)
    claims: Mapping[str, claims_module.Claim] = field(default_factory=dict)
    wording: claims_module.Wording | None = None
    facts: Mapping[str, Mapping[str, Any]] = field(default_factory=dict)  # by case file
    labels: Mapping[str, str] = field(default_factory=dict)  # identifier -> words, in tables

    @classmethod
    def from_repo(cls, summary: Mapping[str, Any], root: Path = REPO) -> Sources:
        protocol = yaml.safe_load((root / "experiments" / "protocol.yaml").read_text())
        configs = {
            path.stem: yaml.safe_load(path.read_text())
            for path in sorted((root / "config").glob("*.yaml"))
        }
        claims_file = root / "report" / "claims.yaml"
        claims, wording = claims_module.load_claims(claims_file)
        labels = ((yaml.safe_load(claims_file.read_text()) or {}).get("wording") or {}).get(
            "labels") or {}
        facts = {path.stem: json.loads(path.read_text())
                 for path in sorted((root / "cases" / "facts").glob("*.json"))}
        return cls(summary=summary, protocol=protocol, configs=configs,
                   claims={claim.id: claim for claim in claims}, wording=wording, facts=facts,
                   labels=_labels(labels))


def _path(data: Any, dotted: str, what: str) -> Any:
    node = data
    for part in dotted.split("."):
        if isinstance(node, Mapping) and part in node:
            node = node[part]
        elif isinstance(node, list) and part.isdigit() and int(part) < len(node):
            node = node[int(part)]
        else:
            raise KeyError(f"{what} has no {dotted!r}")
    if isinstance(node, Mapping | list):
        raise KeyError(f"{what} {dotted!r} is not a single value")
    return node


def _fact(expression: str, sources: Sources) -> tuple[Any, str]:
    """The node at ``<file>:<dotted.path>`` in a case facts file, and the path's last name."""
    match = FACT.fullmatch(expression)
    if not match:
        raise KeyError(f"{expression!r} is not <file>:<dotted.path>")
    name, dotted = match.groups()
    if name not in sources.facts:
        raise KeyError(f"no case facts file {name!r} (cases/facts/{name}.json)")
    node: Any = sources.facts[name]
    for part in dotted.split("."):
        if isinstance(node, Mapping) and part in node:
            node = node[part]
        elif isinstance(node, list) and part.isdigit() and int(part) < len(node):
            node = node[int(part)]
        else:
            raise KeyError(f"cases/facts/{name}.json has no {dotted!r}")
    return node, dotted.rsplit(".", 1)[-1]


def _fact_value(expression: str, sources: Sources) -> Value:
    node, last = _fact(expression, sources)
    if isinstance(node, Mapping | list):
        raise KeyError(f"case fact {expression!r} is not a single value")
    if node is None:
        raise KeyError(f"case fact {expression!r} is null")
    return Value(plain=node, unit=formats.unit_from_name(last))


def _resolve(expression: str, sources: Sources) -> Value:
    if expression.startswith("fact:"):
        return _fact_value(expression[len("fact:"):], sources)
    if expression.startswith("protocol:"):
        dotted = expression[len("protocol:"):]
        return _setting(_path(sources.protocol, dotted, "the protocol"), dotted)
    if expression.startswith("config:"):
        name, _, dotted = expression[len("config:"):].partition(":")
        if name not in sources.configs:
            raise KeyError(f"no configuration file {name!r}")
        return _setting(_path(sources.configs[name], dotted, f"config/{name}.yaml"), dotted)
    if " - " in expression:
        first, second = (part.strip() for part in expression.split(" - ", 1))
        return _difference(_metric(first, sources), _metric(second, sources))
    return Value(metric=_metric(expression, sources), contrast=is_contrast(expression))


def _setting(value: Any, dotted: str) -> Value:
    return Value(plain=value, unit=formats.unit_from_name(dotted.rsplit(".", 1)[-1]),
                 setting=True)


def _metric(key: str, sources: Sources) -> Metric:
    if not KEY.fullmatch(key):
        raise KeyError(f"{key!r} is not a result key")
    return metric(sources.summary, key)


def _difference(first: Metric, second: Metric) -> Value:
    if first.unit != second.unit:
        raise FormatError(f"cannot subtract {second.unit} from {first.unit}")
    if not (first.evaluated and second.evaluated):
        raise FormatError("cannot subtract a metric that was not evaluated")
    return Value(plain=first.value - second.value, unit=first.unit, difference=True)


def _split(body: str) -> tuple[str, str, list[str]]:
    expression, _, spec = body.partition("|")
    name, *args = (spec.strip() or "value").split(":")
    return expression.strip(), name.strip(), [arg.strip() for arg in args]


def render_value(body: str, sources: Sources) -> str:
    """Render one inline placeholder body (the text between the braces)."""
    if body.strip().startswith("claim:"):
        claim_id = body.strip()[len("claim:"):].strip()
        if claim_id not in sources.claims or sources.wording is None:
            raise KeyError(f"no claim {claim_id!r} in report/claims.yaml")
        return claims_module.sentence(sources.claims[claim_id], sources.summary, sources.wording)
    expression, name, args = _split(body)
    if name == "p" and (refused := claims_module.selected_reason(expression, sources.summary)):
        raise FormatError(refused)
    return formats.apply(name, _resolve(expression, sources), args)


def render_table(body: str, sources: Sources) -> str:
    """Render ``table:name [selection] | column "Header" format, ...`` as a Markdown table.

    A cell's unit comes from its column name's suffix (``net_cents``,
    ``held_share``, ...), and a column with ``_vs_`` in its name holds paired
    differences (a column spread by ``across`` takes the unit of the column it
    sums); raises :class:`RenderError` listing every problem.
    """
    head, _, spec = body.partition("|")
    name, *clauses = head.strip()[len("table:"):].split() or [""]
    rows = _fact_rows(name[len("fact:"):], sources) if name.startswith("fact:") else \
        table(sources.summary, name)
    units: dict[str, str | None] = {}
    contrasts: set[str] = set()
    if clauses:
        rows, units, contrasts = select(rows, parse_selection(clauses), name)
    problems: list[str] = []
    columns = []
    for item in spec.split(",") if spec.strip() else []:
        match = COLUMN.match(item)
        if not match:
            problems.append(f"bad column {item.strip()!r}")
            continue
        column, header, form = match.groups()
        format_name, *args = (form or "value").split(":")
        if format_name not in formats.FORMATS and format_name != LABEL:
            problems.append(f"unknown format {format_name!r} for column {column!r}")
        elif rows and column not in rows[0]:
            problems.append(f"no column {column!r}")
        else:
            columns.append((column, header or column, format_name, args))
    if not columns and not problems:
        problems.append("no columns named")
    lines = [
        "| " + " | ".join(header for _, header, _, _ in columns) + " |",
        "|" + "|".join("---" if form in ("value", LABEL) else "---:"
                       for _, _, form, _ in columns) + "|",
    ]
    for index, row in enumerate(rows):
        cells = []
        for column, _, format_name, args in columns:
            cell = row[column]
            if cell is None:
                cells.append("n/a")
            elif isinstance(cell, bool):
                cells.append("yes" if cell else "no")
            elif format_name == LABEL:
                if not isinstance(cell, str) or args:
                    problems.append(f"row {index} column {column!r}: the label format "
                                    "takes no arguments and prints identifiers, not numbers")
                    cells.append("")
                else:
                    cells.append(label(cell, sources.labels))
            else:
                unit = units[column] if column in units else formats.unit_from_name(column)
                resolved = Value(plain=cell, unit=unit,
                                 contrast="_vs_" in column or column in contrasts)
                try:
                    cells.append(formats.apply(format_name, resolved, args))
                except FormatError as error:
                    problems.append(f"row {index} column {column!r}: {error}")
                    cells.append("")
        lines.append("| " + " | ".join(cells) + " |")
    if problems:
        raise RenderError(f"table {name!r}", problems)
    return "\n".join(lines)


# ---------------------------------------------------------------- selecting rows of a table
LABEL = "label"
ROWS_COUNT = "rows_count"
CLAUSES = ("where", "sum", "mean", "by", "across")
CLAUSE_ORDER = {"where": 0, "sum": 1, "mean": 1, "by": 2, "across": 3}
# Units that are quotients (rates, shares and their differences in basis points): a
# pooled figure comes from its numerator and denominator, never by adding or averaging
# per-seed values.
QUOTIENT_UNITS = ("rate", "share", "bps")
QUOTIENT_WORDS = frozenset({"rate", "share", "ratio", "per", "bps", "mean", "avg", "average"})
# Quantiles and extremes: averaged over seeds (a stated mean of each world's value),
# never added up.
LEVEL_WORDS = frozenset({"p50", "p75", "p90", "p95", "p99", "median", "max", "min"})


@dataclass(frozen=True)
class Selection:
    """The clauses after a table's name: rows kept, then grouped and aggregated."""

    where: tuple[tuple[str, str], ...] = ()
    aggregate: str | None = None  # "sum" or "mean"
    columns: tuple[str, ...] = ()  # the aggregated columns
    by: tuple[str, ...] = ()
    across: str | None = None


def parse_selection(words: list[str]) -> Selection:
    """``where col=value ... [sum|mean col,col by col,col [across col]]``, in that order."""
    found: dict[str, list[str]] = {}
    current = None
    for word in words:
        if word in CLAUSES:
            if current is not None and CLAUSE_ORDER[word] <= CLAUSE_ORDER[current]:
                raise ValueError(f"the {word!r} clause cannot follow {current!r} (the order "
                                 "is where, sum or mean, by, across; each once)")
            current = word
            found[word] = []
        elif current is None:
            raise ValueError(f"{word!r} is not a clause; use where, sum, mean, by or across")
        else:
            found[current].append(word)

    def names(clause: str) -> tuple[str, ...]:
        items = tuple(item.strip() for item in " ".join(found[clause]).split(","))
        if not all(KEY.fullmatch(item) and "." not in item for item in items):
            raise ValueError(f"{clause}: name columns separated by commas, got "
                             f"{' '.join(found[clause])!r}")
        return items

    where = []
    for item in found.get("where", []):
        column, equals, wanted = item.partition("=")
        if not equals or not column or not wanted:
            raise ValueError(f"where: {item!r} is not column=value")
        where.append((column, wanted))
    if "where" in found and not where:
        raise ValueError("where: name at least one column=value")
    aggregate = "sum" if "sum" in found else "mean" if "mean" in found else None
    if aggregate is None and ("by" in found or "across" in found):
        raise ValueError("by and across follow sum or mean")
    if aggregate is not None and "by" not in found:
        raise ValueError(f"{aggregate} needs by: the columns that make a group")
    selection = Selection(
        where=tuple(where), aggregate=aggregate,
        columns=names(aggregate) if aggregate else (),
        by=names("by") if aggregate else (),
        across=None)
    if "across" in found:
        if aggregate != "sum":
            raise ValueError("across spreads a sum, not a mean")
        if len(found["across"]) != 1 or len(selection.columns) != 1:
            raise ValueError("across takes one column, and sums one column")
        selection = Selection(selection.where, aggregate, selection.columns, selection.by,
                              found["across"][0])
    return selection


def _text(cell: Any) -> str:
    """A cell as a where clause reads it."""
    if isinstance(cell, bool):
        return "true" if cell else "false"
    return "null" if cell is None else str(cell)


def aggregation_refused(column: str, how: str) -> str | None:
    """Why ``column`` cannot be summed or averaged over rows, or ``None``."""
    parts = set(column.split("_"))
    if formats.unit_from_name(column) in QUOTIENT_UNITS or parts & QUOTIENT_WORDS:
        return (f"{column!r} is a rate, share or mean: pool it from its numerator and "
                "denominator (its result key), never add up or average the rows")
    if how == "sum" and parts & LEVEL_WORDS:
        return f"{column!r} is a quantile or an extreme: it does not add up (use mean)"
    return None


def _number(cell: Any, column: str) -> int | float | None:
    if cell is None:
        return None
    if isinstance(cell, bool) or not isinstance(cell, int | float):
        raise ValueError(f"column {column!r} holds {cell!r}, not a number")
    return cell


def _aggregate(cells: list[Any], how: str, column: str) -> int | float | None:
    numbers = [_number(cell, column) for cell in cells]
    if any(number is None for number in numbers):
        return None  # a row with nothing measured leaves its group's figure unknown
    total = sum(numbers)
    return total if how == "sum" else total / len(numbers)


def select(rows: list[dict[str, Any]], selection: Selection,
           name: str) -> tuple[list[dict[str, Any]], dict[str, str | None], set[str]]:
    """The rows ``selection`` keeps and aggregates, the units of spread columns, and
    which of them hold paired differences; raises :class:`RenderError` listing every
    problem."""
    problems = []
    columns = set(rows[0]) if rows else set()
    named = [column for column, _ in selection.where] + list(selection.by) + \
        list(selection.columns) + ([selection.across] if selection.across else [])
    problems += [f"no column {column!r}" for column in dict.fromkeys(named)
                 if column not in columns]
    if selection.aggregate:
        problems += [reason for column in selection.columns
                     if (reason := aggregation_refused(column, selection.aggregate))]
        if overlap := set(selection.columns) & set(selection.by):
            problems.append(f"{sorted(overlap)} both group and are aggregated")
    if problems:
        raise RenderError(f"table {name!r}", problems)
    kept = [row for row in rows
            if all(_text(row.get(column)) == wanted for column, wanted in selection.where)]
    if not kept:
        wanted = " ".join(f"{column}={value}" for column, value in selection.where)
        raise RenderError(f"table {name!r}", [f"no rows match where {wanted}"])
    if not selection.aggregate:
        return kept, {}, set()
    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = {}
    for row in kept:
        groups.setdefault(tuple(row.get(column) for column in selection.by), []).append(row)
    out = []
    try:
        if selection.across:
            [summed] = selection.columns
            spread = list(dict.fromkeys(row.get(selection.across) for row in kept))
            titles = [_text(value) for value in spread]
            if clash := set(titles) & set(selection.by):
                raise ValueError(f"spread columns {sorted(clash)} clash with the groups")
            for key, members in groups.items():
                record = dict(zip(selection.by, key, strict=True))
                for value, title in zip(spread, titles, strict=True):
                    cells = [row.get(summed) for row in members
                             if row.get(selection.across) == value]
                    record[title] = _aggregate(cells, "sum", summed) if cells else 0
                out.append(record)
            unit = formats.unit_from_name(summed)
            return out, {title: unit for title in titles}, (
                set(titles) if "_vs_" in summed else set())
        for key, members in groups.items():
            record = dict(zip(selection.by, key, strict=True))
            for column in selection.columns:
                record[column] = _aggregate([row.get(column) for row in members],
                                            selection.aggregate, column)
            record[ROWS_COUNT] = len(members)
            out.append(record)
    except ValueError as error:
        raise RenderError(f"table {name!r}", [str(error)]) from error
    return out, {}, set()


def _labels(data: Any) -> dict[str, str]:
    labels = dict(data or {})
    for key, text in labels.items():
        if not isinstance(key, str) or not isinstance(text, str) or not text:
            raise ValueError(f"wording.labels.{key}: give the words as text")
    return labels


def label(identifier: str, labels: Mapping[str, str]) -> str:
    """An identifier, or a comma-separated list of them, in words: its entry in
    ``wording.labels``, else its words split at underscores; an empty list is "none"."""
    if not identifier.strip():
        return "none"
    return ", ".join(labels.get(item, item.replace("_", " "))
                     for item in (part.strip() for part in identifier.split(",")))


def _fact_rows(expression: str, sources: Sources) -> list[dict[str, Any]]:
    node, _ = _fact(expression, sources)
    if not isinstance(node, list) or not all(isinstance(row, Mapping) for row in node):
        raise KeyError(f"case fact {expression!r} is not a list of records")
    return [dict(row) for row in node]


def render_facts(body: str, sources: Sources) -> str:
    """Render ``facts:<file>:<path> ["Header" "Header"] | name "Label" format, ...``: one
    row per named single value of the record at the path, each formatted in the unit of
    its own name; raises :class:`RenderError` listing every problem."""
    head, _, spec = body.partition("|")
    match = FACTS_HEAD.fullmatch(head.strip())
    if not match:
        raise KeyError(f"{head.strip()!r} is not facts:<file>:<dotted.path>")
    expression, first, second = match.groups()
    record, _ = _fact(expression, sources)
    if not isinstance(record, Mapping):
        raise KeyError(f"case fact {expression!r} is not a record")
    problems: list[str] = []
    lines = [f"| {first or 'Fact'} | {second or 'Value'} |", "|---|---:|"]
    for item in spec.split(",") if spec.strip() else []:
        found = COLUMN.match(item)
        if not found:
            problems.append(f"bad entry {item.strip()!r}")
            continue
        key, label, form = found.groups()
        format_name, *args = (form or "value").split(":")
        if format_name not in formats.FORMATS:
            problems.append(f"unknown format {format_name!r} for fact {key!r}")
            continue
        if key not in record:
            problems.append(f"no fact {key!r} in {expression!r}")
            continue
        value = record[key]
        if isinstance(value, Mapping | list):
            problems.append(f"fact {key!r} is not a single value")
            continue
        if value is None:
            problems.append(f"fact {key!r} is null")
            continue
        if isinstance(value, bool):
            if form is not None:
                problems.append(f"fact {key!r} is yes or no and takes no format")
                continue
            cell = "yes" if value else "no"
        else:
            try:
                cell = formats.apply(format_name, Value(plain=value,
                                                        unit=formats.unit_from_name(key)), args)
            except FormatError as error:
                problems.append(f"fact {key!r}: {error}")
                cell = ""
        lines.append(f"| {label or key} | {cell} |")
    if len(lines) == 2 and not problems:
        problems.append("no facts named")
    if problems:
        raise RenderError(f"facts {expression!r}", problems)
    return "\n".join(lines)


def render(text: str, sources: Sources, name: str = "template") -> str:
    """Render a template's text; raises :class:`RenderError` listing every problem."""
    problems: list[str] = []
    out_lines = []
    for number, line in enumerate(text.split("\n"), start=1):
        stripped = line.strip()
        block = PLACEHOLDER.fullmatch(stripped)
        if block and block.group(1).strip().startswith(("table:", "facts:")):
            render_block = render_facts if block.group(1).strip().startswith("facts:") \
                else render_table
            try:
                out_lines.append(render_block(block.group(1), sources))
            except (KeyError, FormatError, ValueError) as error:
                problems.append(f"line {number}: {_message(error)}")
            continue

        def replace(match: re.Match[str], number: int = number) -> str:
            body = match.group(1)
            if body.strip().startswith(("table:", "facts:")):
                problems.append(f"line {number}: a table placeholder must be on its own line")
                return ""
            try:
                return render_value(body, sources)
            except (KeyError, FormatError, ValueError) as error:
                problems.append(f"line {number}: {{{{{body.strip()}}}}}: {_message(error)}")
                return ""

        out_lines.append(PLACEHOLDER.sub(replace, line))
    if "{{" in "\n".join(out_lines) or "}}" in "\n".join(out_lines):
        problems.append("unbalanced placeholder braces")
    if problems:
        raise RenderError(name, problems)
    return "\n".join(out_lines)


def _message(error: Exception) -> str:
    return str(error.args[0]) if isinstance(error, KeyError) and error.args else str(error)


@dataclass(frozen=True)
class Document:
    template: Path
    output: Path

    @property
    def name(self) -> str:
        return self.output.as_posix()


def documents(templates: Path = TEMPLATES) -> list[Document]:
    """Every template and the repository path of the document it produces."""
    return [
        Document(template=path, output=path.relative_to(templates))
        for path in sorted(templates.rglob("*.md"))
    ]


def render_document(document: Document, sources: Sources, root: Path = REPO) -> str:
    """The full text of a rendered document, with the generated-file header."""
    template = document.template
    template_name = (template.relative_to(root).as_posix() if template.is_relative_to(root)
                     else template.name)
    body = render(document.template.read_text(), sources, document.name)
    return HEADER.format(template=template_name) + body


NOT_RENDERED = "NOT_RENDERED.txt"


def render_all(sources: Sources, out_root: Path, templates: Path = TEMPLATES,
               root: Path = REPO, *, strict: bool = False) -> list[Path]:
    """Render every template into ``out_root``; returns the paths written.

    Into the repository (``out_root`` is ``root``), or with ``strict``, a document
    that cannot be rendered fails the render and nothing is written. Anywhere else
    (a development or small run's ``docs`` folder) the documents whose result keys or
    case facts the run has are written, the others are skipped: they and their
    problems are listed in ``out_root/NOT_RENDERED.txt``, a copy of a skipped
    document left there by an earlier render is removed, and a one-line notice is
    printed. A render that skips nothing removes an old list.
    """
    strict = strict or Path(out_root).resolve() == Path(root).resolve()
    rendered: dict[Document, str] = {}
    skipped: dict[Document, RenderError] = {}
    for doc in documents(templates):
        try:
            rendered[doc] = render_document(doc, sources, root)
        except RenderError as error:
            if strict:
                raise
            skipped[doc] = error
    written = []
    for doc, text in rendered.items():
        target = out_root / doc.output
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        written.append(target)
    notice = Path(out_root) / NOT_RENDERED
    if skipped:
        lines = []
        for doc, error in skipped.items():
            (Path(out_root) / doc.output).unlink(missing_ok=True)
            lines += [f"{doc.name}:", *(f"  {problem}" for problem in error.problems)]
        notice.parent.mkdir(parents=True, exist_ok=True)
        notice.write_text("Documents not rendered from this summary, and why:\n"
                          + "\n".join(lines) + "\n")
        written.append(notice)
        print(f"report: {len(skipped)} of {len(skipped) + len(rendered)} documents not "
              f"rendered from this summary (see {notice})", file=sys.stderr)
    else:
        notice.unlink(missing_ok=True)
    return written


def out_of_sync(sources: Sources, out_root: Path, templates: Path = TEMPLATES,
                root: Path = REPO) -> list[str]:
    """Documents whose committed text differs from a fresh render."""
    problems = []
    for doc in documents(templates):
        target = out_root / doc.output
        try:
            expected = render_document(doc, sources, root)
        except RenderError as error:
            problems.append(str(error))
            continue
        if not target.exists():
            problems.append(f"{doc.name}: not rendered (run python -m report render)")
        elif target.read_text() != expected:
            problems.append(f"{doc.name}: differs from its template and the results "
                            "(run python -m report render)")
    return problems
