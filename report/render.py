class RenderError(ValueError):
    """A template could not be rendered; ``problems`` lists each one."""

    def __init__(self, name: str, problems: list[str]):
        self.problems = problems
        super().__init__(f"{name}: " + "; ".join(problems))


@dataclass
class Sources:
    """Where placeholders look values up."""

    summary: Mapping[str, Any]
    protocol: Mapping[str, Any] = field(default_factory=dict)
    configs: Mapping[str, Mapping[str, Any]] = field(default_factory=dict)
    claims: Mapping[str, claims_module.Claim] = field(default_factory=dict)
    wording: claims_module.Wording | None = None
    facts: Mapping[str, Mapping[str, Any]] = field(default_factory=dict)  # by case file
    labels: Mapping[str, str] = field(default_factory=dict)  # identifier -> words, in tables

    @classmethod
    def from_repo(cls, summary: Mapping[str, Any], root: Path = REPO) -> Sources:
        protocol = yaml.safe_load((root / "experiments" / "protocol.yaml").read_text())
        configs = {
            path.stem: yaml.safe_load(path.read_text())
            for path in sorted((root / "config").glob("*.yaml"))
        }
        claims_file = root / "report" / "claims.yaml"
        claims, wording = claims_module.load_claims(claims_file)
        labels = ((yaml.safe_load(claims_file.read_text()) or {}).get("wording") or {}).get(
            "labels") or {}
        facts = {path.stem: json.loads(path.read_text())
                 for path in sorted((root / "cases" / "facts").glob("*.json"))}
        return cls(summary=summary, protocol=protocol, configs=configs,
                   claims={claim.id: claim for claim in claims}, wording=wording, facts=facts,
                   labels=_labels(labels))


def _path(data: Any, dotted: str, what: str) -> Any:
    node = data
    for part in dotted.split("."):
        if isinstance(node, Mapping) and part in node:
            node = node[part]
        elif isinstance(node, list) and part.isdigit() and int(part) < len(node):
            node = node[int(part)]
        else:
            raise KeyError(f"{what} has no {dotted!r}")
    if isinstance(node, Mapping | list):
        raise KeyError(f"{what} {dotted!r} is not a single value")
    return node


def _fact(expression: str, sources: Sources) -> tuple[Any, str]:
    """The node at ``<file>:<dotted.path>`` in a case facts file, and the path's last name."""
    match = FACT.fullmatch(expression)
    if not match:
        raise KeyError(f"{expression!r} is not <file>:<dotted.path>")
    name, dotted = match.groups()
    if name not in sources.facts:
        raise KeyError(f"no case facts file {name!r} (cases/facts/{name}.json)")
    node: Any = sources.facts[name]
    for part in dotted.split("."):
        if isinstance(node, Mapping) and part in node:
            node = node[part]
        elif isinstance(node, list) and part.isdigit() and int(part) < len(node):
            node = node[int(part)]
        else:
            raise KeyError(f"cases/facts/{name}.json has no {dotted!r}")
    return node, dotted.rsplit(".", 1)[-1]


def _fact_value(expression: str, sources: Sources) -> Value:
    node, last = _fact(expression, sources)
    if isinstance(node, Mapping | list):
        raise KeyError(f"case fact {expression!r} is not a single value")
    if node is None:
        raise KeyError(f"case fact {expression!r} is null")
    return Value(plain=node, unit=formats.unit_from_name(last))


def _resolve(expression: str, sources: Sources) -> Value:
    if expression.startswith("fact:"):
        return _fact_value(expression[len("fact:"):], sources)
    if expression.startswith("protocol:"):
        dotted = expression[len("protocol:"):]
        return _setting(_path(sources.protocol, dotted, "the protocol"), dotted)
    if expression.startswith("config:"):
        name, _, dotted = expression[len("config:"):].partition(":")
        if name not in sources.configs:
            raise KeyError(f"no configuration file {name!r}")
        return _setting(_path(sources.configs[name], dotted, f"config/{name}.yaml"), dotted)
    if " - " in expression:
        first, second = (part.strip() for part in expression.split(" - ", 1))
        return _difference(_metric(first, sources), _metric(second, sources))
    return Value(metric=_metric(expression, sources), contrast=is_contrast(expression))


def _setting(value: Any, dotted: str) -> Value:
    return Value(plain=value, unit=formats.unit_from_name(dotted.rsplit(".", 1)[-1]),
                 setting=True)


def _metric(key: str, sources: Sources) -> Metric:
    if not KEY.fullmatch(key):
        raise KeyError(f"{key!r} is not a result key")
    return metric(sources.summary, key)


def _difference(first: Metric, second: Metric) -> Value:
    if first.unit != second.unit:
        raise FormatError(f"cannot subtract {second.unit} from {first.unit}")
    if not (first.evaluated and second.evaluated):
        raise FormatError("cannot subtract a metric that was not evaluated")
    return Value(plain=first.value - second.value, unit=first.unit, difference=True)


def _split(body: str) -> tuple[str, str, list[str]]:
    expression, _, spec = body.partition("|")
    name, *args = (spec.strip() or "value").split(":")
    return expression.strip(), name.strip(), [arg.strip() for arg in args]


def render_value(body: str, sources: Sources) -> str:
    """Render one inline placeholder body (the text between the braces)."""
    if body.strip().startswith("cell:"):
        return render_cell(body, sources)
    if body.strip().startswith("claim:"):
        claim_id = body.strip()[len("claim:"):].strip()
        if claim_id not in sources.claims or sources.wording is None:
            raise KeyError(f"no claim {claim_id!r} in report/claims.yaml")
        return claims_module.sentence(sources.claims[claim_id], sources.summary, sources.wording)
    expression, name, args = _split(body)
    if name == "p" and (refused := claims_module.selected_reason(expression, sources.summary)):
        raise FormatError(refused)
    return formats.apply(name, _resolve(expression, sources), args)


def render_table(body: str, sources: Sources) -> str:
    """Render ``table:name [selection] | column "Header" format, ...`` as a Markdown table.

    A cell's unit comes from its column name's suffix (``net_cents``,
    ``held_share``, ...), and a column with ``_vs_`` in its name holds paired
    differences (a column spread by ``across`` takes the unit of the column it
    sums); raises :class:`RenderError` listing every problem.
    """
    head, _, spec = body.partition("|")
    name, *clauses = head.strip()[len("table:"):].split() or [""]
    rows = _fact_rows(name[len("fact:"):], sources) if name.startswith("fact:") else \
        table(sources.summary, name)
    units: dict[str, str | None] = {}
    contrasts: set[str] = set()
    if clauses:
        rows, units, contrasts = select(rows, parse_selection(clauses), name,
                                        unevaluated=unevaluated_worlds(sources.summary))
    problems: list[str] = []
    columns = []
    for item in spec.split(",") if spec.strip() else []:
        match = COLUMN.match(item)
        if not match:
            problems.append(f"bad column {item.strip()!r}")
            continue
        column, header, form = match.groups()
        format_name, *args = (form or "value").split(":")
        if format_name not in formats.FORMATS and format_name not in (LABEL, IDENTIFIER):
            problems.append(f"unknown format {format_name!r} for column {column!r}")
        elif rows and column not in rows[0]:
            problems.append(f"no column {column!r}")
        else:
            columns.append((column, header or column, format_name, args))
    if not columns and not problems:
        problems.append("no columns named")
    lines = [
        "| " + " | ".join(header for _, header, _, _ in columns) + " |",
        "|" + "|".join("---" if form in ("value", LABEL, IDENTIFIER) else "---:"
                       for _, _, form, _ in columns) + "|",
    ]
    for index, row in enumerate(rows):
        cells = []
        for column, _, format_name, args in columns:
            try:
                cells.append(_cell(row, column, format_name, args, units, contrasts, sources))
            except FormatError as error:
                problems.append(f"row {index} column {column!r}: {error}")
                cells.append("")
        lines.append("| " + " | ".join(cells) + " |")
    if problems:
        raise RenderError(f"table {name!r}", problems)
    return "\n".join(lines)


def _cell(row: Mapping[str, Any], column: str, format_name: str, args: list[str],
          units: Mapping[str, str | None], contrasts: set[str], sources: Sources) -> str:
    """One value of a result table's row as text; raises :class:`FormatError`."""
    cell = row[column]
    if cell is None:
        return "n/a"
    if isinstance(cell, bool):
        return "yes" if cell else "no"
    if format_name == IDENTIFIER:
        if isinstance(cell, int | str) and not args and formats.unit_from_name(column) is None:
            return str(cell)
        raise FormatError("the id format prints an identifier (a seed, an order id) as it "
                          "is, not a quantity, and takes no arguments")
    if format_name == LABEL:
        if not isinstance(cell, str) or args:
            raise FormatError("the label format takes no arguments and prints identifiers, "
                              "not numbers")
        return label(cell, sources.labels)
    unit = units[column] if column in units else formats.unit_from_name(column)
    return formats.apply(format_name, Value(plain=cell, unit=unit,
                                            contrast="_vs_" in column or column in contrasts),
                         args)


def render_cell(body: str, sources: Sources) -> str:
    """Render ``cell:name [selection] | column format`` inline: the value in ``column`` of
    the one row of the result table ``name`` that the selection leaves (:func:`select`,
    with every refusal it makes for a table); raises :class:`RenderError` unless exactly
    one row remains and one column is named, without a header."""
    head, _, spec = body.partition("|")
    name, *clauses = head.strip()[len("cell:"):].split() or [""]
    where = f"cell {name!r}"
    if name.startswith("fact:"):
        raise RenderError(where, ["a cell comes from a result table; a case fact is fact:"])
    rows = table(sources.summary, name)
    units: dict[str, str | None] = {}
    contrasts: set[str] = set()
    if clauses:
        rows, units, contrasts = select(rows, parse_selection(clauses), name,
                                        unevaluated=unevaluated_worlds(sources.summary))
    match = COLUMN.match(spec) if "," not in spec else None
    if not match or not match.group(1) or match.group(2) is not None:
        raise RenderError(where, ["name one column and its format, without a header: "
                                  "| column format"])
    column, _, form = match.groups()
    format_name, *args = (form or "value").split(":")
    problems = []
    if format_name not in formats.FORMATS and format_name not in (LABEL, IDENTIFIER):
        problems.append(f"unknown format {format_name!r} for column {column!r}")
    if len(rows) != 1:
        problems.append(f"the selection leaves {len(rows)} rows; a cell needs exactly one")
    elif column not in rows[0]:
        problems.append(f"no column {column!r}")
    if problems:
        raise RenderError(where, problems)
    try:
        return _cell(rows[0], column, format_name, args, units, contrasts, sources)
    except FormatError as error:
        raise RenderError(where, [f"column {column!r}: {error}"]) from error


